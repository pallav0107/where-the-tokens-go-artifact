#!/usr/bin/env python3
"""Data behind Fig. 1: stacked shares of all orchestrator tokens and of list-price cost by token kind.

  python tools/cost_figure_data.py dat [--check]

dat  renders papers/agent2027-cost/generated/cost_shares.dat for pgfplots from the committed
     evidence/cost_table.json (the same shares as Table I, recorded); --check exits 1 if the
     committed file is stale (CI).

Segments, in stacking order: cache reads; new-suffix cache writes (all writes minus re-writes);
re-writes after an idle gap of over an hour with no other observed cause; re-writes after a gap of
five to sixty minutes; all other re-writes (within the entry lifetime, tool-list/prompt/version
change, model change, compaction); uncached input; output. Each bar must add up to 100% and the
re-writes must not exceed the writes, or it is BLOCKED. No number is computed here that is not
already a share in cost_table.json; this only regroups and scales to percent.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence_lib import REPO  # noqa: E402

EVIDENCE_FILE = REPO / "evidence" / "cost_table.json"
DAT = REPO / "papers" / "agent2027-cost" / "generated" / "cost_shares.dat"
SEGMENTS = ("read", "newwrite", "rwidle", "rwmid", "rwother", "fresh", "output")
BARS = (("tokens", "token_share", 1), ("cost", "cost_share", 0))   # name, share key, y position
OTHER_CAUSES = ("within_lifetime", "config_change", "model_change", "compaction")
TOL = 1e-5   # cost_table rounds some cost shares to six decimals


def blocked(msg: str) -> None:
    sys.exit(f"BLOCKED: {msg}")


def load(path: Path) -> dict[str, Any]:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def rows(a: dict[str, Any]) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    for bar, key, _ in BARS:
        s = a[key]
        cause = {c: a["rewrite_by_cause"][c][key] for c in a["rewrite_by_cause"]}
        rw_all = a["rewrite_all"][key]
        writes = s["write1h"] + s["write5m"]
        if rw_all > writes + TOL:
            blocked(f"{bar}: re-writes ({rw_all}) exceed writes ({writes})")
        if abs(sum(cause.values()) - rw_all) > TOL:
            blocked(f"{bar}: re-write causes do not add up to all re-writes")
        seg = {"read": s["read"], "newwrite": writes - rw_all, "rwidle": cause["gap_gt_60min"],
               "rwmid": cause["gap_5_to_60min"], "rwother": sum(cause[c] for c in OTHER_CAUSES),
               "fresh": s["fresh"], "output": s["output"]}
        total = sum(seg.values())
        if abs(total - 1.0) > TOL:
            blocked(f"{bar}: shares add up to {total}, not 1")
        out[bar] = {k: v * 100 for k, v in seg.items()}
    return out


def render_dat(evidence: dict[str, Any]) -> str:
    r = rows(evidence["aggregates"])
    lines = ["# GENERATED by tools/cost_figure_data.py dat from evidence/cost_table.json -- DO NOT EDIT.",
             "# Percent of all orchestrator tokens (tokens) and of list-price cost as recorded (cost).",
             "bar y " + " ".join(SEGMENTS)]
    for bar, _, y in BARS:
        lines.append(f"{bar.capitalize()} {y} " + " ".join(f"{r[bar][k]:.3f}" for k in SEGMENTS))
    return "\n".join(lines) + "\n"


def dat_command(evidence_path: Path, dat_path: Path, check: bool) -> int:
    text = render_dat(load(evidence_path))
    if check:
        current = dat_path.read_text(encoding="utf-8").replace("\r\n", "\n") if dat_path.is_file() else None
        if current != text:
            print(f"FAIL: {dat_path.name} is stale or missing (run `python tools/cost_figure_data.py dat` and commit)")
            return 1
        print(f"PASS: {dat_path.name} matches {Path(evidence_path).name}")
        return 0
    dat_path.parent.mkdir(parents=True, exist_ok=True)
    dat_path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {dat_path.name}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("dat", help="evidence/cost_table.json -> generated/cost_shares.dat")
    d.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    return dat_command(EVIDENCE_FILE, DAT, args.check)


if __name__ == "__main__":
    raise SystemExit(main())
