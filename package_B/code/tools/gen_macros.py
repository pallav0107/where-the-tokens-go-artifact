#!/usr/bin/env python3
"""CREATE stage: every figure in every evidence/*.json -> a LaTeX macro.

Writes papers/<paper>/generated/numbers.tex for each paper. Any evidence file with a
provenance block contributes (new producers just drop a JSON in evidence/). Macro
names must be unique across files.

  --check   regenerate in memory and exit 1 if a committed numbers.tex is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence_lib import (MACRO_NAME, REPO, evidence_files, format_value,  # noqa: E402
                          load_json, sha256_bytes)

PAPERS = REPO / "papers"


def paper_dirs() -> list[Path]:
    return sorted(p for p in PAPERS.iterdir() if (p / "main.tex").is_file())


def render() -> str:
    lines = [
        "% GENERATED by tools/gen_macros.py from evidence/*.json -- DO NOT EDIT BY HAND.",
        "% Every number in the paper's prose must come from a macro defined here.",
    ]
    body: list[str] = []
    seen: dict[str, str] = {}
    for path in evidence_files():
        data = load_json(path)
        prov = data.get("provenance")
        if not isinstance(prov, dict):
            sys.exit(f"FAIL: {path.name} has no provenance block")
        normalized = path.read_bytes().replace(b"\r\n", b"\n")  # same hash on Windows and CI
        lines.append(f"% {path.name}: sha256 {sha256_bytes(normalized)[:16]}, "
                     f"generated {prov.get('generated_at')}")
        for name, fig in sorted(data.get("figures", {}).items()):
            if not MACRO_NAME.match(name):
                sys.exit(f"FAIL: {path.name}: invalid macro name {name!r}")
            if name in seen:
                sys.exit(f"FAIL: macro {name} defined in both {seen[name]} and {path.name}")
            seen[name] = path.name
            value = format_value(fig["value"], fig["format"])
            body.append(f"\\newcommand{{\\{name}}}{{{value}\\xspace}}% {path.stem}: {fig['desc']}")
    lines.append(f"% {len(seen)} macros")
    return "\n".join(lines + ["\\RequirePackage{xspace}"] + body) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    stale = []
    for paper in paper_dirs():
        out = paper / "generated" / "numbers.tex"
        if args.check:
            current = out.read_text(encoding="utf-8") if out.is_file() else ""
            if current.replace("\r\n", "\n") != text:
                stale.append(str(out.relative_to(REPO)))
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {out.relative_to(REPO)}")
    if stale:
        print("FAIL: stale generated macros (run `make macros` and commit):")
        for s in stale:
            print(f"  - {s}")
        return 1
    if args.check:
        print("PASS: generated macros are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
