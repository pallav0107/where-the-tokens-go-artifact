#!/usr/bin/env python3
"""Data behind Fig. 1: what the first request after each injected pause read back and wrote.

  python tools/pause_figure_data.py dat [--check]

dat  renders papers/agent2027-cost/generated/pause_points.dat for pgfplots from the committed
     evidence/pause_experiment.json (the registered direct expiry check, experiments/PREREG_pause.md);
     --check exits 1 if the committed file is stale (CI).

One row per injected pause, condition B (five-minute caching, 360 s pauses) first, then C (one-hour
caching, 3660 s pause), each sorted by the cached prefix before the pause, with an empty slot between
the two conditions. Columns, in thousands of tokens: head = tokens read back by the first request
after the pause; rewrite = its re-written tokens by the paper's positional model
(max(0, min(C, read + write) - read), tools/cache_writes.py); newsuffix = the rest of its write;
prefix = the cached prefix C before the pause. head + rewrite must not exceed C, or it is BLOCKED.
Nothing here is new measurement; this only restates committed rows.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence_lib import REPO  # noqa: E402
from pause_figures import pause_rewrite  # noqa: E402

EVIDENCE_FILE = REPO / "evidence" / "pause_experiment.json"
DAT = REPO / "papers" / "agent2027-cost" / "generated" / "pause_points.dat"
COLUMNS = ("head", "rewrite", "newsuffix", "prefix")


def blocked(msg: str) -> None:
    sys.exit(f"BLOCKED: {msg}")


def load(path: Path) -> dict[str, Any]:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def rows(a: dict[str, Any]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    x = 0
    for cond, de in (("B", a["direct_expiry"]), ("C", a["condition_c"]["direct_expiry"])):
        if len(de["pauses"]) != de["n"]:
            blocked(f"{cond}: {len(de['pauses'])} pause rows, {de['n']} declared")
        if out:
            x += 1          # empty slot between the conditions
        for p in sorted(de["pauses"], key=lambda r: r["prefix_before"]):
            pre, rd, wr = p["prefix_before"], p["read_after"], p["write_after"]
            rw = pause_rewrite(p)
            if rd + rw > pre:
                blocked(f"{cond}: read back {rd} + re-written {rw} exceed the cached prefix {pre}")
            x += 1
            out.append({"x": x, "cond": cond, "head": rd / 1000, "rewrite": rw / 1000,
                        "newsuffix": (wr - rw) / 1000, "prefix": pre / 1000})
    return out


def render_dat(evidence: dict[str, Any]) -> str:
    lines = ["# GENERATED by tools/pause_figure_data.py dat from evidence/pause_experiment.json -- DO NOT EDIT.",
             "# Per injected pause, first request after it, thousands of tokens.",
             "x cond " + " ".join(COLUMNS)]
    for r in rows(evidence["aggregates"]):
        lines.append(f"{r['x']} {r['cond']} " + " ".join(f"{r[k]:.3f}" for k in COLUMNS))
    return "\n".join(lines) + "\n"


def dat_command(evidence_path: Path, dat_path: Path, check: bool) -> int:
    text = render_dat(load(evidence_path))
    if check:
        current = dat_path.read_text(encoding="utf-8").replace("\r\n", "\n") if dat_path.is_file() else None
        if current != text:
            print(f"FAIL: {dat_path.name} is stale or missing (run `python tools/pause_figure_data.py dat` and commit)")
            return 1
        print(f"PASS: {dat_path.name} matches {Path(evidence_path).name}")
        return 0
    dat_path.parent.mkdir(parents=True, exist_ok=True)
    dat_path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {dat_path.name}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("dat", help="evidence/pause_experiment.json -> generated/pause_points.dat")
    d.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    return dat_command(EVIDENCE_FILE, DAT, args.check)


if __name__ == "__main__":
    raise SystemExit(main())
